-- ============================================================================
-- 7. FUNCIÓN AUXILIAR DE INMUTABILIDAD DE HIJOS
--
-- FOR UPDATE coordina cambios concurrentes. Una operación sobre hijos bloquea
-- la cabecera y un cierre concurrente espera. Si el cierre gana el bloqueo,
-- la operación posterior ve el estado cerrado y se rechaza.
-- ============================================================================

create function public.assert_presupuesto_borrador(
  p_presupuesto_id bigint,
  p_club_id bigint,
  p_operacion text
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_estado text;
begin
  select p.estado
  into v_estado
  from public.presupuestos as p
  where p.id_presupuesto = p_presupuesto_id
    and p.club_id = p_club_id
  for update;

  if not found then
    raise exception
      'No existe el presupuesto % en el club % al intentar %.',
      p_presupuesto_id,
      p_club_id,
      p_operacion;
  end if;

  if v_estado <> 'borrador' then
    raise exception
      'No se puede %: el presupuesto % está cerrado.',
      p_operacion,
      p_presupuesto_id;
  end if;
end;
$function$;

revoke all
on function public.assert_presupuesto_borrador(bigint, bigint, text)
from public;


-- ============================================================================
-- 8. INMUTABILIDAD DE PRESUPUESTO_PROGRAMAS
--
-- INSERT comprueba NEW, DELETE comprueba OLD y UPDATE comprueba ambos. Esto
-- impide mover una relación desde un presupuesto cerrado a uno abierto.
-- ============================================================================

create function public.enforce_presupuesto_programas_borrador()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if tg_op = 'INSERT' then
    perform public.assert_presupuesto_borrador(
      new.presupuesto_id,
      new.club_id,
      'insertar una relación presupuesto-programa'
    );
    return new;
  end if;

  if tg_op = 'DELETE' then
    perform public.assert_presupuesto_borrador(
      old.presupuesto_id,
      old.club_id,
      'eliminar una relación presupuesto-programa'
    );
    return old;
  end if;

  perform public.assert_presupuesto_borrador(
    old.presupuesto_id,
    old.club_id,
    'modificar la relación presupuesto-programa de origen'
  );

  perform public.assert_presupuesto_borrador(
    new.presupuesto_id,
    new.club_id,
    'modificar la relación presupuesto-programa de destino'
  );

  return new;
end;
$function$;

revoke all
on function public.enforce_presupuesto_programas_borrador()
from public;


-- ============================================================================
-- 9. COMPATIBILIDAD ENTRE PRESUPUESTO Y PROGRAMA
-- ============================================================================

create function public.validate_presupuesto_programa()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_presupuesto public.presupuestos%rowtype;
  v_programa public.programas%rowtype;
begin
  select p.*
  into v_presupuesto
  from public.presupuestos as p
  where p.id_presupuesto = new.presupuesto_id
    and p.club_id = new.club_id;

  if not found then
    raise exception
      'No existe el presupuesto % en el club indicado.',
      new.presupuesto_id;
  end if;

  select p.*
  into v_programa
  from public.programas as p
  where p.id_programa = new.programa_id
    and p.club_id = new.club_id;

  if not found then
    raise exception
      'El programa % no existe o no pertenece al club del presupuesto.',
      new.programa_id;
  end if;

  if v_programa.club_id <> v_presupuesto.club_id then
    raise exception
      'El programa % y el presupuesto % pertenecen a clubes distintos.',
      new.programa_id,
      new.presupuesto_id;
  end if;

  if v_programa.tipo_programa
     is distinct from v_presupuesto.tipo_programa
  then
    raise exception
      'Programa incompatible: tipo del programa = %, tipo del presupuesto = %.',
      v_programa.tipo_programa,
      v_presupuesto.tipo_programa;
  end if;

  if v_programa.anio is null
     or v_programa.anio < v_presupuesto.anio_inicio
     or v_programa.anio > v_presupuesto.anio_fin
  then
    raise exception
      'Programa incompatible: año del programa = %, periodo del presupuesto = %-%.',
      coalesce(v_programa.anio::text, 'NULL'),
      v_presupuesto.anio_inicio,
      v_presupuesto.anio_fin;
  end if;

  -- Cuando hay subvención, el programa debe formar parte de la convocatoria.
  if v_presupuesto.subvencion_id is not null
     and not exists (
       select 1
       from public.subvencion_programas as sp
       where sp.subvencion_id = v_presupuesto.subvencion_id
         and sp.programa_id = new.programa_id
         and sp.club_id = new.club_id
     )
  then
    raise exception
      'El programa % no está vinculado a la subvención % del presupuesto.',
      new.programa_id,
      v_presupuesto.subvencion_id;
  end if;

  return new;
end;
$function$;

revoke all
on function public.validate_presupuesto_programa()
from public;


