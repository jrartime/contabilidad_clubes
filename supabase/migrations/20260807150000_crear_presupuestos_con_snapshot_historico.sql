begin;

-- ============================================================================
-- PRESUPUESTOS CON SNAPSHOT HISTÓRICO DE CONCEPTOS
--
-- Esta migración crea:
--   1. public.presupuestos
--   2. public.presupuesto_programas
--   3. public.presupuesto_partidas
--
-- Decisiones principales:
--   - Un presupuesto pertenece a un club y puede abarcar varios programas.
--   - Las partidas pertenecen al presupuesto completo, no a cada programa.
--   - Solo existe una partida oficial por concepto y presupuesto.
--   - Mientras el presupuesto está en borrador se consulta el catálogo actual
--     de public.conceptos.
--   - Al cerrar, nombre, naturaleza y subvencionabilidad se copian a las
--     partidas dentro de la misma transacción y quedan congelados.
--   - concepto_id se conserva para comparar posteriormente la ejecución con
--     public.contabilidad.concepto_id.
--
-- Esta migración no modifica Storage ni utiliza presupuesto_previsto como
-- detalle presupuestario.
-- ============================================================================


-- ============================================================================
-- 1. GUARDS PREVIOS
-- ============================================================================

do $presupuestos_preflight$
declare
  v_tabla text;
begin
  -- Las tablas de las que depende el modelo deben existir antes de continuar.
  foreach v_tabla in array array[
    'clubes',
    'programas',
    'conceptos',
    'subvenciones',
    'subvencion_programas'
  ]
  loop
    if to_regclass(format('public.%I', v_tabla)) is null then
      raise exception
        'Migración de Presupuestos abortada: falta la tabla public.%.',
        v_tabla;
    end if;
  end loop;

  -- La presencia de cualquiera de las tablas nuevas indicaría una instalación
  -- parcial o un cambio no auditado. En ese caso no se sobrescribe nada.
  foreach v_tabla in array array[
    'presupuestos',
    'presupuesto_programas',
    'presupuesto_partidas'
  ]
  loop
    if to_regclass(format('public.%I', v_tabla)) is not null then
      raise exception
        'Migración de Presupuestos abortada: public.% ya existe.',
        v_tabla;
    end if;
  end loop;

  -- Verifica el modelo de autorización desplegado por la Migración 1.
  if to_regprocedure('public.can_access_club(bigint)') is null then
    raise exception
      'Migración abortada: no existe public.can_access_club(bigint).';
  end if;

  if to_regprocedure('public.can_edit_club(bigint)') is null then
    raise exception
      'Migración abortada: no existe public.can_edit_club(bigint).';
  end if;

  -- El cierre y el snapshot solo reconocen las dos naturalezas auditadas.
  if exists (
    select 1
    from public.conceptos as c
    where c.naturaleza is null
       or c.naturaleza not in ('gasto', 'ingreso')
  ) then
    raise exception
      'Migración abortada: existen conceptos con naturaleza desconocida.';
  end if;

  -- Los programas existentes deben usar las familias soportadas por el nuevo
  -- modelo para que la comparación estructurada sea segura.
  if exists (
    select 1
    from public.programas as p
    where p.tipo_programa is null
       or p.tipo_programa not in (
         'clubes',
         'eventos',
         'eedd_ctd_discapacidad'
       )
  ) then
    raise exception
      'Migración abortada: existen programas con tipo_programa desconocido.';
  end if;
end;
$presupuestos_preflight$;


-- ============================================================================
-- 2. CLAVES ÚNICAS COMPUESTAS PARA EL AISLAMIENTO ESTRUCTURAL POR CLUB
--
-- Las PK existentes garantizan la unicidad del identificador. Estas claves
-- adicionales permiten que las nuevas FKs comprueben simultáneamente el ID y
-- el club, sin confiar solo en RLS ni en el frontend.
-- ============================================================================

alter table public.programas
  add constraint programas_id_programa_club_id_key
  unique (id_programa, club_id);

alter table public.conceptos
  add constraint conceptos_id_concepto_club_id_key
  unique (id_concepto, club_id);

alter table public.subvenciones
  add constraint subvenciones_id_subvencion_club_id_key
  unique (id_subvencion, club_id);


-- ============================================================================
-- 3. CABECERAS DE PRESUPUESTO
-- ============================================================================

create table public.presupuestos (
  -- Identificador técnico del presupuesto.
  id_presupuesto bigint generated by default as identity primary key,

  -- Agrupa las distintas versiones de un mismo presupuesto lógico.
  serie_id uuid not null default gen_random_uuid(),

  -- Club propietario y ámbito de aislamiento RLS.
  club_id bigint not null,

  -- Convocatoria o expediente opcional. NULL identifica un presupuesto
  -- interno independiente de una subvención.
  subvencion_id bigint,

  nombre text not null,

  -- Familia funcional común con programas.tipo_programa.
  tipo_programa text not null,

  -- Clasificación estructurada para EEDD, CTD o EEDD discapacidad.
  subtipo_programa text,

  -- Forma de expresar el periodo: ejercicio, temporada o evento.
  periodo_tipo text not null,

  anio_inicio integer not null,
  anio_fin integer not null,
  fecha_inicio date not null,
  fecha_fin date not null,

  -- Número de versión dentro de serie_id.
  version integer not null default 1,

  -- La primera versión del módulo solo utiliza borrador y cerrado.
  estado text not null default 'borrador',

  observaciones text,

  -- Se conserva el presupuesto si el usuario creador se elimina.
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  cerrado_at timestamptz,

  constraint presupuestos_club_id_fkey
    foreign key (club_id)
    references public.clubes (id_club)
    on delete restrict,

  -- Impide estructuralmente relacionar una subvención de otro club.
  constraint presupuestos_subvencion_club_fkey
    foreign key (subvencion_id, club_id)
    references public.subvenciones (id_subvencion, club_id)
    on delete restrict,

  constraint presupuestos_created_by_fkey
    foreign key (created_by)
    references auth.users (id)
    on delete set null,

  constraint presupuestos_tipo_programa_check
    check (
      tipo_programa in ('clubes', 'eventos', 'eedd_ctd_discapacidad')
    ),

  -- No se admite NULL transitorio para EEDD/CTD porque la tabla es nueva y no
  -- hay presupuestos históricos que migrar.
  constraint presupuestos_subtipo_programa_check
    check (
      (
        tipo_programa in ('clubes', 'eventos')
        and subtipo_programa is null
      )
      or
      (
        tipo_programa = 'eedd_ctd_discapacidad'
        and subtipo_programa is not null
        and subtipo_programa in ('eedd', 'ctd', 'eedd_discapacidad')
      )
    ),

  constraint presupuestos_periodo_tipo_check
    check (periodo_tipo in ('ejercicio', 'temporada', 'evento')),

  constraint presupuestos_anios_check
    check (anio_fin >= anio_inicio),

  constraint presupuestos_fechas_check
    check (fecha_fin >= fecha_inicio),

  -- Las fechas exactas deben coincidir con el intervalo de años declarado.
  constraint presupuestos_fechas_anios_check
    check (
      extract(year from fecha_inicio)::integer = anio_inicio
      and extract(year from fecha_fin)::integer = anio_fin
    ),

  constraint presupuestos_version_check
    check (version > 0),

  constraint presupuestos_estado_check
    check (estado in ('borrador', 'cerrado')),

  -- cerrado_at solo puede existir cuando la cabecera está cerrada.
  constraint presupuestos_cierre_check
    check (
      (estado = 'borrador' and cerrado_at is null)
      or
      (estado = 'cerrado' and cerrado_at is not null)
    ),

  -- Esta clave soporta las FKs compuestas de las tablas hijas.
  constraint presupuestos_id_club_key
    unique (id_presupuesto, club_id),

  constraint presupuestos_serie_version_key
    unique (club_id, serie_id, version)
);


-- ============================================================================
-- 4. PROGRAMAS CONTABLES INCLUIDOS EN CADA PRESUPUESTO
-- ============================================================================

create table public.presupuesto_programas (
  id_presupuesto_programa bigint generated by default as identity primary key,
  club_id bigint not null,
  presupuesto_id bigint not null,
  programa_id bigint not null,
  created_at timestamptz not null default now(),

  constraint presupuesto_programas_presupuesto_club_fkey
    foreign key (presupuesto_id, club_id)
    references public.presupuestos (id_presupuesto, club_id)
    on delete restrict,

  constraint presupuesto_programas_programa_club_fkey
    foreign key (programa_id, club_id)
    references public.programas (id_programa, club_id)
    on delete restrict,

  constraint presupuesto_programas_presupuesto_programa_key
    unique (presupuesto_id, programa_id)
);


-- ============================================================================
-- 5. PARTIDAS OFICIALES Y SNAPSHOT HISTÓRICO
--
-- Los tres campos snapshot son administrados por el proceso de cierre:
--   - En borrador pueden permanecer NULL y se usa public.conceptos.
--   - Al cerrar se sobrescriben con el catálogo vigente en ese instante.
--   - En informes cerrados deben usarse los snapshots.
-- ============================================================================

create table public.presupuesto_partidas (
  id_partida bigint generated by default as identity primary key,
  club_id bigint not null,
  presupuesto_id bigint not null,
  concepto_id bigint not null,
  descripcion text,
  importe_presupuestado numeric(14, 2) not null,
  orden integer not null default 0,

  -- Interpretación histórica congelada al cerrar el presupuesto.
  concepto_nombre_snapshot text,
  naturaleza_snapshot text,
  subvencionabilidad_snapshot text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint presupuesto_partidas_presupuesto_club_fkey
    foreign key (presupuesto_id, club_id)
    references public.presupuestos (id_presupuesto, club_id)
    on delete restrict,

  constraint presupuesto_partidas_concepto_club_fkey
    foreign key (concepto_id, club_id)
    references public.conceptos (id_concepto, club_id)
    on delete restrict,

  constraint presupuesto_partidas_importe_check
    check (importe_presupuestado >= 0),

  constraint presupuesto_partidas_orden_check
    check (orden >= 0),

  constraint presupuesto_partidas_naturaleza_snapshot_check
    check (
      naturaleza_snapshot is null
      or naturaleza_snapshot in ('gasto', 'ingreso')
    ),

  constraint presupuesto_partidas_subvencionabilidad_snapshot_check
    check (
      subvencionabilidad_snapshot is null
      or subvencionabilidad_snapshot in (
        'subvencionable',
        'no_subvencionable',
        'condicionada'
      )
    ),

  -- En v1 existe una sola partida oficial por concepto. En el futuro puede
  -- añadirse presupuesto_partida_detalles dependiendo de id_partida sin
  -- alterar este modelo principal.
  constraint presupuesto_partidas_presupuesto_concepto_key
    unique (presupuesto_id, concepto_id)
);


