begin;

-- ============================================================================
-- FASE 1 DE ADMINISTRACIÓN: DATOS LEGALES DEL CLUB Y JUNTA DIRECTIVA
--
-- Esta migración añade:
--   1. Datos de registro legal en public.clubes (número de registro
--      autonómico y fecha de constitución). El NIF ya existente actúa como
--      CIF del club.
--   2. public.junta_directiva: cargos de la junta directiva con su periodo
--      de vigencia, para poder acreditar en cada momento quién representa
--      al club (necesario en solicitudes y justificaciones de subvenciones).
--
-- Un club solo puede tener un presidente, un secretario y un tesorero
-- activos a la vez; puede tener varios vicepresidentes y vocales activos.
-- ============================================================================


-- ============================================================================
-- 1. GUARDS PREVIOS
-- ============================================================================

do $preflight$
begin
  if to_regclass('public.clubes') is null then
    raise exception 'Migración abortada: no existe public.clubes.';
  end if;

  if to_regclass('public.junta_directiva') is not null then
    raise exception 'Migración abortada: public.junta_directiva ya existe.';
  end if;

  if to_regprocedure('public.can_access_club(bigint)') is null then
    raise exception 'Migración abortada: no existe public.can_access_club(bigint).';
  end if;

  if to_regprocedure('public.can_edit_club(bigint)') is null then
    raise exception 'Migración abortada: no existe public.can_edit_club(bigint).';
  end if;
end;
$preflight$;


-- ============================================================================
-- 2. DATOS LEGALES DEL CLUB
-- ============================================================================

alter table public.clubes
  add column numero_registro text,
  add column fecha_constitucion date;

comment on column public.clubes.numero_registro is
  'Número de registro del club en el Registro de Entidades Deportivas del Principado de Asturias.';

comment on column public.clubes.fecha_constitucion is
  'Fecha de constitución del club.';

comment on column public.clubes.nif is
  'CIF del club.';


-- ============================================================================
-- 3. JUNTA DIRECTIVA
-- ============================================================================

create table public.junta_directiva (
  id_cargo bigint generated by default as identity primary key,
  club_id bigint not null,

  persona_nombre text not null,
  persona_dni text,
  cargo text not null,

  fecha_inicio date not null,
  fecha_fin date,
  activo boolean not null default true,

  observaciones text,

  created_at timestamptz not null default now(),

  constraint junta_directiva_club_id_fkey
    foreign key (club_id)
    references public.clubes (id_club)
    on delete restrict,

  constraint junta_directiva_cargo_check
    check (
      cargo in ('presidente', 'vicepresidente', 'secretario', 'tesorero', 'vocal')
    ),

  constraint junta_directiva_fechas_check
    check (fecha_fin is null or fecha_fin >= fecha_inicio)
);

comment on table public.junta_directiva is
  'Cargos de la junta directiva del club, con su periodo de vigencia (mandato).';

-- Solo puede haber un cargo unipersonal activo de cada tipo por club.
-- Vicepresidente y vocal quedan fuera porque puede haber varios simultáneos.
create unique index junta_directiva_cargo_unico_activo_idx
  on public.junta_directiva (club_id, cargo)
  where activo and cargo in ('presidente', 'secretario', 'tesorero');

create index junta_directiva_club_activo_idx
  on public.junta_directiva (club_id, activo);


-- ============================================================================
-- 4. ROW LEVEL SECURITY
-- ============================================================================

alter table public.junta_directiva enable row level security;

create policy junta_directiva_select_by_club
on public.junta_directiva for select to authenticated
using (public.can_access_club(club_id));

create policy junta_directiva_insert_by_club
on public.junta_directiva for insert to authenticated
with check (public.can_edit_club(club_id));

create policy junta_directiva_update_by_club
on public.junta_directiva for update to authenticated
using (public.can_edit_club(club_id))
with check (public.can_edit_club(club_id));

create policy junta_directiva_delete_by_club
on public.junta_directiva for delete to authenticated
using (public.can_edit_club(club_id));


-- ============================================================================
-- 5. PRIVILEGIOS
-- ============================================================================

revoke all on table public.junta_directiva from anon;

grant select, insert, update, delete on table public.junta_directiva to authenticated;

revoke all on sequence public.junta_directiva_id_cargo_seq from anon;

grant usage, select on sequence public.junta_directiva_id_cargo_seq to authenticated;

commit;


